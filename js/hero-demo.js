/* Hero demo — the LIVE widget conversation as the hero module (premium layer, Queue #12).
   A second, in-page instance of the add-on: same rule-based engine (js/logic.js), same
   chips, same callback flow, same local lead + hand-off logs (pv_leads / pv_handoffs) as
   the corner widget — so a callback completed here lands in leads.html exactly like one
   from the widget (cross-surface proof preserved). Its own conversation is NOT persisted
   (it is a showcase surface; the corner widget keeps the persistent conversation).
   Selectors are data-demo-* throughout: the corner widget's data-chat-* surface and the
   flow battery's selectors are never touched.
   No-JS: the panel keeps its printed static transcript (in the HTML) — complete and readable.
   Reduced motion: the scripted exchange renders instantly, no autoplay delays. */
(function () {
  'use strict';
  var L = window.ChatLogic;
  var panel = document.querySelector('[data-demo-panel]');
  if (!L || !panel) return;
  var msgsEl = panel.querySelector('[data-demo-msgs]');
  var reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  function read(key, dflt) { try { var v = JSON.parse(localStorage.getItem(key)); return v == null ? dflt : v; } catch (e) { return dflt; } }
  function write(key, v) { try { localStorage.setItem(key, JSON.stringify(v)); } catch (e) {} }

  /* Build the live controls (the static transcript ships without them). */
  var note = panel.querySelector('[data-demo-static-note]');
  if (note) note.remove();
  var chipsEl = document.createElement('div');
  chipsEl.className = 'chat-chips';
  chipsEl.innerHTML = L.CHIPS.map(function (c, i) {
    return '<button type="button" class="chip" data-demo-chip="' + i + '">' + c.label + '</button>';
  }).join('');
  var actionsEl = document.createElement('div');
  actionsEl.className = 'chat-actions';
  actionsEl.innerHTML = '<a class="wa-btn" data-demo-wa href="' + L.BIZ.whatsappUrl + '" target="_blank" rel="noopener">WhatsApp a person</a>' +
    '<button type="button" class="clear-btn" data-demo-replay>Replay the demo</button>';
  var form = document.createElement('form');
  form.className = 'chat-form';
  form.setAttribute('data-demo-form', '');
  form.innerHTML = '<label for="demo-chat-input">Type your question for the demo bot</label>' +
    '<input id="demo-chat-input" data-demo-input type="text" autocomplete="off" placeholder="Ask about prices, hours…">' +
    '<button type="submit">Send</button>';
  panel.appendChild(chipsEl); panel.appendChild(actionsEl); panel.appendChild(form);
  var input = form.querySelector('[data-demo-input]');

  var messages = [], flow = null, pendingName = null, timers = [];
  function render() {
    msgsEl.innerHTML = messages.map(function (m) {
      return '<div class="msg ' + m.from + '">' + m.text.replace(/</g, '&lt;') + '<span class="stamp">Demo clock · ' + L.DEMO_CLOCK.split(' · ')[1].replace(' (fixed demo clock)', '') + '</span></div>';
    }).join('');
    msgsEl.scrollTop = msgsEl.scrollHeight;
  }
  function push(from, text) { messages.push({ from: from, text: text }); render(); }
  function later(fn, ms) { if (reduced) { fn(); return; } timers.push(setTimeout(fn, ms)); }
  function clearTimers() { timers.forEach(clearTimeout); timers = []; }

  function greetText() {
    return 'Hello — I\u2019m the ' + L.BIZ.shortName + ' FAQ assistant. ' + L.DEMO_LABEL + '. Ask me about services, prices, hours or bookings, or tap a suggestion below.';
  }
  /* The scripted, user-steerable exchange: greeting -> hours -> whitening price.
     Every bot line is generated by ChatLogic from the BIZ object at run time. */
  function playScript() {
    clearTimers(); messages = []; flow = null; pendingName = null; render();
    later(function () { push('bot', greetText()); }, 350);
    later(function () { push('user', 'What are your opening hours?'); }, 1200);
    later(function () { push('bot', L.answerFor('What are your opening hours?').text); }, 2000);
    later(function () { push('user', 'How much is teeth whitening?'); }, 2900);
    later(function () { push('bot', L.answerFor('How much is teeth whitening?').text); }, 3700);
  }

  function startCallback() {
    flow = 'name'; pendingName = null;
    push('bot', 'I can arrange that. First — what is your full name?');
  }
  function respond(text) { push('bot', L.answerFor(text).text); }
  function handleUser(text) {
    push('user', text);
    if (flow === 'name') {
      var v = L.validateName(text);
      if (!v.ok) { push('bot', v.error); return; }
      pendingName = v.value; flow = 'phone';
      push('bot', 'Thank you, ' + v.value.split(' ')[0] + '. And the best Pakistani mobile number to call you back on? (For example 0321 555 0142.)');
      return;
    }
    if (flow === 'phone') {
      var p = L.validatePhonePK(text);
      if (!p.ok) { push('bot', p.error); return; }
      var out = L.addLead(read('pv_leads', []), pendingName, p.value, 'index.html (hero demo)');
      write('pv_leads', out.leads);
      flow = null; pendingName = null;
      push('bot', L.callbackConfirmText(out.lead));
      return;
    }
    respond(text);
  }

  chipsEl.addEventListener('click', function (e) {
    var b = e.target.closest('[data-demo-chip]'); if (!b) return;
    clearTimers();
    var chip = L.CHIPS[Number(b.getAttribute('data-demo-chip'))];
    if (chip.action === 'callback') startCallback();
    else { push('user', chip.label); respond(chip.query); }
    input.focus();
  });
  form.addEventListener('submit', function (e) {
    e.preventDefault();
    var text = input.value.trim();
    if (!text) { push('bot', 'You sent an empty message — type a question about our services, prices, hours or bookings, or tap a suggestion above.'); input.focus(); return; }
    input.value = ''; clearTimers();
    handleUser(text.slice(0, 500));
    input.focus();
  });
  actionsEl.addEventListener('click', function (e) {
    if (e.target.closest('[data-demo-replay]')) { playScript(); }
    if (e.target.closest('[data-demo-wa]')) {
      var out = L.addHandoff(read('pv_handoffs', []), 'index.html (hero demo)');
      write('pv_handoffs', out.log);
    }
  });

  /* Autoplay once, when the hero first comes into view. */
  var started = false;
  function start() { if (started) return; started = true; playScript(); }
  if (reduced || !('IntersectionObserver' in window)) { start(); }
  else {
    var io = new IntersectionObserver(function (entries) {
      if (entries.some(function (en) { return en.isIntersecting; })) { start(); io.disconnect(); }
    }, { threshold: 0.25 });
    io.observe(panel);
  }
})();
